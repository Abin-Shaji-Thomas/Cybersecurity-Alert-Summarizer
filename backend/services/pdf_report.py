"""Incident report as PDF (reportlab platypus: paragraphs + tables)."""
import io
from collections import Counter
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

SEV_COLOR = {"Low": "#2e7d32", "Medium": "#f9a825", "High": "#ef6c00", "Critical": "#c62828"}


def _p(text, style):
    return Paragraph(escape(str(text or "")), style)


def _table(rows, widths, header=True):
    t = Table(rows, colWidths=widths, repeatRows=1 if header else 0)
    style = [("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#999999")),
             ("VALIGN", (0, 0), (-1, -1), "TOP"),
             ("FONTSIZE", (0, 0), (-1, -1), 8)]
    if header:
        style += [("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1f2a37")),
                  ("TEXTCOLOR", (0, 0), (-1, 0), colors.white)]
    t.setStyle(TableStyle(style))
    return t


def build_pdf(inc, alerts, entities):
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=1.6 * cm, rightMargin=1.6 * cm,
                            topMargin=1.5 * cm, bottomMargin=1.5 * cm, title=f"Incident {inc['id']}")
    ss = getSampleStyleSheet()
    small = ss["BodyText"].clone("small", fontSize=8, leading=10)
    body = ss["BodyText"]
    s = inc["slots"]
    sev = inc["severity"]
    out = [
        Paragraph(f"Incident #{inc['id']}: {escape(inc['title'])}", ss["Title"]),
        Paragraph(f"<font color='{SEV_COLOR.get(sev, '#000000')}'><b>Severity: {sev}</b></font> &nbsp; | &nbsp; "
                  f"{escape(s.get('time_window', ''))} &nbsp; | &nbsp; {inc['n_alerts']} alerts", body),
        Spacer(1, 8),
        Paragraph("Summary (template filling)", ss["Heading2"]), _p(inc["summary_template"], body),
        Paragraph("Extractive summary (TF-IDF)", ss["Heading3"]), _p(inc["summary_extractive"], small),
    ]
    if inc.get("summary_abstractive"):
        out += [Paragraph("AI summary (pretrained model)", ss["Heading3"]), _p(inc["summary_abstractive"], small)]

    out += [Paragraph("Recommended action", ss["Heading2"]), _p(inc["recommended_action"], body),
            Paragraph("Filled template slots", ss["Heading2"])]
    slot_rows = [["Slot", "Value"]]
    for key in ["what_happened", "attacker", "users", "targets", "time_window", "phases", "severity", "frequency", "outcome",
                "mitre_techniques", "mitre_tactics", "keywords", "top_rare_alerts"]:
        v = s.get(key)
        if isinstance(v, list):
            v = "; ".join(map(str, v))
        slot_rows.append([key.replace("_", " "), _p(v, small)])
    out.append(_table(slot_rows, [4 * cm, 13.6 * cm]))

    # timeline: consecutive identical alerts collapsed
    out += [Paragraph("Timeline", ss["Heading2"])]
    tl = [["Start", "End", "Count", "Alert", "Source", "Host"]]
    last = None
    for a in alerts:
        key = (a["description"], a["src_ip"], a["host"])
        if last and last[0] == key:
            last[1][1] = a["timestamp"][11:19]
            last[1][2] += 1
            continue
        row = [a["timestamp"][11:19], a["timestamp"][11:19], 1, a["description"], a["src_ip"] or a["user"] or "", a["host"]]
        tl.append(row)
        last = (key, row)
        if len(tl) > 40:
            break
    tl = [tl[0]] + [[r[0], r[1], str(r[2]), _p(r[3], small), _p(r[4], small), _p(r[5], small)] for r in tl[1:]]
    out.append(_table(tl, [1.7 * cm, 1.7 * cm, 1.3 * cm, 7.4 * cm, 3 * cm, 2.5 * cm]))
    if len(tl) > 40:
        out.append(_p("(timeline truncated to the first 40 events)", small))

    out += [Paragraph("Entities (NER)", ss["Heading2"])]
    cnt = Counter((e["text"], e["label"]) for e in entities)
    er = [["Entity", "Label", "Mentions"]] + [[_p(t, small), l, str(c)] for (t, l), c in cnt.most_common(25)]
    out.append(_table(er, [9 * cm, 4 * cm, 3 * cm]))

    if inc.get("relations"):
        out += [Paragraph("Relations", ss["Heading2"])]
        rr = [["Subject", "Relation", "Object", "Count"]] + [
            [_p(r["subject"], small), r["relation"], _p(r["object"], small), str(r["count"])] for r in inc["relations"][:25]]
        out.append(_table(rr, [6.5 * cm, 3 * cm, 6 * cm, 2 * cm]))

    out += [Spacer(1, 10), _p("Generated by Cybersecurity Alert Summarizer (local NLP pipeline). "
                              "Data: AIT Alert Data Set (CC BY 4.0).", small)]
    doc.build(out)
    return buf.getvalue()
